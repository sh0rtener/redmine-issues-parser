CREATE TABLE redmine.issues (
	id int4 NOT NULL,
	project_id int4 NULL,
	project_name varchar(255) NULL,
	tracker_id int4 NULL,
	tracker_name varchar(255) NULL,
	status_id int4 NULL,
	status_name varchar(255) NULL,
	is_closed bool NULL,
	priority_id int4 NULL,
	priority_name varchar(255) NULL,
	author_id int4 NULL,
	author_name varchar(255) NULL,
	assigned_to_id int4 NULL,
	assigned_to_name varchar(255) NULL,
	category_id int4 NULL,
	category_name varchar(255) NULL,
	subject varchar(255) NULL,
	description text NULL,
	start_date date NULL,
	due_date date NULL,
	done_ratio int2 NULL,
	is_private bool NULL,
	estimated_hours numeric NULL,
	total_estimated_hours numeric NULL,
	created_on timestamptz NULL,
	updated_on timestamptz NULL,
	closed_on timestamptz NULL,
	CONSTRAINT issues_pkey PRIMARY KEY (id)
);